export function createMatches(teams) {
  const grouped = teams.reduce((acc, team) => {
    acc[team.group] = acc[team.group] || [];
    acc[team.group].push(team);
    return acc;
  }, {});

  return Object.keys(grouped).sort().flatMap((group, groupIndex) => {
    const groupTeams = grouped[group];
    return pairings.map(([homeIndex, awayIndex], roundIndex) => {
      const home = groupTeams[homeIndex];
      const away = groupTeams[awayIndex];
      const kickoff = new Date(Date.UTC(2026, 5, 11 + groupIndex + Math.floor(roundIndex / 2), 18 + (roundIndex % 2) * 3));
      return {
        id: `g${group}${roundIndex + 1}`,
        stage: "小组赛",
        group,
        kickoff: kickoff.toISOString(),
        time: `小组第 ${Math.floor(roundIndex / 2) + 1} 轮 / 开球时间待导入`,
        venue: "官方场馆待导入",
        home: home.id,
        away: away.id,
        marketHeat: Math.round(48 + Math.min(45, (home.value + away.value) / 45)),
        weather: "待赛前 24 小时更新天气与草皮",
        referee: "待 FIFA 公布裁判组",
        rest: [4 + (roundIndex % 3), 4 + ((roundIndex + 1) % 3)],
        dataStatus: "可赛前分析",
      };
    });
  });
}

